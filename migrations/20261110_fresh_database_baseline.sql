-- Run only through scripts/bootstrap-database.mjs against a verified empty database.
-- This baseline creates the legacy tables that predate the additive migrations.
CREATE TABLE admin_user (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar NOT NULL UNIQUE,
  name varchar NOT NULL,
  "isActive" boolean NOT NULL DEFAULT true
);

CREATE TABLE admin_user_provider (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider varchar NOT NULL,
  "providerId" varchar NOT NULL,
  "adminUserId" integer REFERENCES admin_user(id),
  UNIQUE (provider, "providerId")
);

CREATE TABLE personal_info (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar NOT NULL,
  location varchar NOT NULL,
  linkedin varchar NOT NULL,
  portfolio varchar NOT NULL,
  summary text NOT NULL,
  title varchar NOT NULL,
  email varchar NOT NULL,
  "resumeUrl" varchar
);

CREATE TABLE project (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar NOT NULL,
  description text NOT NULL,
  status varchar,
  "caseStudy" jsonb,
  "isDraft" boolean NOT NULL DEFAULT true,
  "isFeatured" boolean NOT NULL DEFAULT false
);

CREATE TABLE technology (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar NOT NULL
);

CREATE TABLE project_link (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url varchar NOT NULL,
  type varchar NOT NULL DEFAULT 'github',
  "projectId" integer REFERENCES project(id)
);

CREATE TABLE project_technologies_technology (
  "projectId" integer NOT NULL REFERENCES project(id) ON UPDATE CASCADE ON DELETE CASCADE,
  "technologyId" integer NOT NULL REFERENCES technology(id) ON UPDATE CASCADE ON DELETE CASCADE,
  PRIMARY KEY ("projectId", "technologyId")
);
CREATE INDEX project_technologies_technology_project ON project_technologies_technology ("projectId");
CREATE INDEX project_technologies_technology_technology ON project_technologies_technology ("technologyId");

CREATE TABLE experience (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company varchar NOT NULL,
  location varchar,
  url varchar,
  description text NOT NULL
);

CREATE TABLE experience_role (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar NOT NULL,
  duration varchar,
  "startDate" varchar,
  "endDate" varchar,
  "isCurrent" boolean NOT NULL DEFAULT false,
  "experienceId" integer REFERENCES experience(id)
);

CREATE TABLE experience_responsibility (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  description text NOT NULL,
  "order" integer NOT NULL DEFAULT 0,
  "roleId" integer REFERENCES experience_role(id)
);

CREATE TABLE skill (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category varchar NOT NULL
);

CREATE TABLE skill_item (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar NOT NULL,
  "skillId" integer REFERENCES skill(id)
);

CREATE TABLE resume (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "filePath" varchar NOT NULL,
  url varchar NOT NULL,
  "createdAt" timestamp NOT NULL DEFAULT now()
);

CREATE TABLE ai_config (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  provider varchar(50) NOT NULL,
  "apiKey" varchar NOT NULL,
  model varchar,
  "baseUrl" varchar,
  "anthropicVersion" varchar,
  "isActive" boolean NOT NULL DEFAULT false,
  "createdAt" timestamp NOT NULL DEFAULT now(),
  "updatedAt" timestamp NOT NULL DEFAULT now()
);
